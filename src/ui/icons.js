export function icon(name, { size = 24, title } = {}) {
  const rows = ICONS[name]
  if (!rows) return ''
  const h = rows.length
  const w = Math.max(...rows.map((r) => r.length))
  let rects = ''
  rows.forEach((row, y) => {
    let x = 0
    while (x < row.length) {
      const ch = row[x]
      if (ch === '.') {
        x++
        continue
      }
      let run = 1
      while (row[x + run] === ch) run++
      const fill = ch === '#' ? 'currentColor' : PAL[ch]
      rects += `<rect x="${x}" y="${y}" width="${run}" height="1" fill="${fill}"/>`
      x += run
    }
  })
  const label = title ? `role="img" aria-label="${title}"` : 'aria-hidden="true"'
  const sw = (size * w) / Math.max(w, h)
  const sh = (size * h) / Math.max(w, h)
  return `<svg ${label} width="${sw}" height="${sh}" viewBox="0 0 ${w} ${h}" shape-rendering="crispEdges">${rects}</svg>`
}
